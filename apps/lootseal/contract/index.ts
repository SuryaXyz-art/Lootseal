// This file's main purpose is to export the compiled contract. The imports below
// resolve against contract/managed/lootseal, which is generated by `yarn compile`
// (gitignored). Write contract/lootseal.compact first, then compile.
import { CompiledContract } from '@midnight-ntwrk/midnight-js-protocol/compact-js';
import path from 'node:path';

export {
  Contract,
  ledger,
  pureCircuits,
  DropState,
  RequestStatus,
  ListingStatus,
  type Witnesses,
  type Ledger,
  type ImpureCircuits,
  type PureCircuits,
} from './managed/lootseal/contract/index.js';
import { Contract } from './managed/lootseal/contract/index.js';
import { witnesses } from './witnesses.js';
const currentDir = path.resolve(new URL(import.meta.url).pathname, '..');
export const zkConfigPath = path.resolve(currentDir, 'managed', 'lootseal');

export const CompiledLootsealContract = CompiledContract.make(
  'LootsealContract',
  Contract,
).pipe(
  CompiledContract.withWitnesses(witnesses),
  CompiledContract.withCompiledFileAssets(zkConfigPath),
);

// The drop registry (contract/registry.compact), wired by hand because it
// has witnesses of its own.
export {
  Contract as RegistryContract,
  ledger as registryLedger,
  type Ledger as RegistryLedger,
} from './managed/registry/contract/index.js';
import { Contract as RegistryContract } from './managed/registry/contract/index.js';
import { registryWitnesses } from './registry-witnesses.js';
export const registryZkConfigPath = path.resolve(currentDir, 'managed', 'registry');

export const CompiledRegistryContract = CompiledContract.make(
  'RegistryContract',
  RegistryContract,
).pipe(
  CompiledContract.withWitnesses(registryWitnesses),
  CompiledContract.withCompiledFileAssets(registryZkConfigPath),
);
